'use strict';
const assert=require('node:assert/strict');
const {measureTournament,buildExitIqReport,BASELINE,POLICIES}=require('./exitIq');
const {evaluateRule}=require('./triggeredExitV2');
const {normalize,RULES,PRIMARY}=require('./quickExit');
const at=Date.parse('2026-11-16T10:00:20+05:30'),MIN=60000,iso=t=>new Date(t).toISOString(),start=(Math.floor(at/MIN)+1)*MIN;
const q={tier:'C',instrumentKey:'NSE_FO|test',contractId:'NIFTY TEST CE',ask:100,bid:99.5,lotSize:65,observedAt:iso(at),analysisAt:iso(at-1000)};
const mk=(i,o=100,h=101,l=99,c=100)=>[iso(start+i*MIN),o,h,l,c];
const base=Array.from({length:30},(_,i)=>mk(i));
const run=(candles,entry=q,now=start+30*MIN)=>measureTournament({entry,candles,now});
let r=run(base);
assert.equal(r.status,'MEASURED');assert.equal(Object.keys(r.results).length,POLICIES.length);
assert.equal(r.results.STAGNATION_15.reason,'STAGNATION');assert.equal(r.results.STAGNATION_15.minutes,15);
assert.equal(r.results.STAGNATION_15.afterlife[15].status,'MEASURED_REFERENCE_ONLY');
assert.equal(r.results[BASELINE].afterlife[5].status,'UNAVAILABLE');
assert.equal(r.results[BASELINE].referenceExitPrice,100);
const both=base.slice();both[0]=mk(0,100,116,90,110);
r=run(both);
assert.equal(r.results[BASELINE].reason,'STOP');assert.equal(r.results[BASELINE].referenceExitPrice,92);
assert.equal(r.results.STEP_LOCK.reason,'STOP');
const gap=base.slice();gap[0]=mk(0,89,95,88,93);
assert.equal(run(gap).results[BASELINE].referenceExitPrice,89);
const rise=base.slice();rise[0]=mk(0,100,108,99,107);rise[1]=mk(1,107,113,106,111);rise[2]=mk(2,106,107,104,105);
r=run(rise);
assert.equal(r.results.STEP_LOCK.reason,'RATCHET');assert.equal(r.results.STEP_LOCK.referenceExitPrice,106,'gap through floor gets worse opening price');
assert.equal(r.results.STEP_LOCK.finalFloorPoints,8);
assert.equal(r.results.STEP_LOCK.scenarios.STRESS_2PT.estimatedNetRupees<r.results.STEP_LOCK.scenarios.BASE_1PT.estimatedNetRupees,true);
const same=base.slice();same[0]=mk(0,100,107,99,106);same[1]=mk(1,106,108,105,107);
assert.notEqual(run(same).results.STEP_LOCK.exitCandleAt,iso(start),'new floor never retroactively applies to earlier low');
const close=base.slice();close[0]=mk(0,100,107,99,100);
assert.equal(run(close).results.STEP_LOCK.reason,'RATCHET_AT_CLOSE');
assert.equal(run(close).results.STEP_LOCK.referenceExitPrice,100,'no imaginary fill at raised floor');
assert.equal(run(base.slice(0,29)).reason,'INCOMPLETE_OR_INVALID_COMMON_PATH');
assert.equal(run([...base,base[0]]).status,'UNAVAILABLE');
assert.equal(run(base.map((x,i)=>i===2?mk(i,100,98,97,100):x)).status,'UNAVAILABLE');
assert.equal(run(base.map((x,i)=>i===2?mk(i,null,100,99,100):x)).status,'UNAVAILABLE');
assert.equal(run(base,q,start+29*MIN).reason,'COMMON_HORIZON_NOT_COMPLETE');
assert.equal(run(base,{...q,analysisAt:iso(at-16000)}).reason,'ENTRY_QUOTE_UNAVAILABLE');
assert.equal(run(base,{...q,observedAt:'2026-11-16T15:10:10+05:30',analysisAt:'2026-11-16T15:10:09+05:30'}).reason,'FULL_COMMON_SESSION_WINDOW_UNAVAILABLE');
const cmp=evaluateRule({entry:q.ask,quantity:q.lotSize,firstCandleMs:start,rows:normalize(rise),rule:RULES.find(x=>x.id===PRIMARY)});
assert.deepEqual(run(rise).results[BASELINE].scenarios,cmp.scenarios,'existing research baseline unchanged');
const event={eventId:'e',session:'2026-11-16',family:'ORB_1M',direction:'UP',timestamp:iso(at),candidateQuotes:[q]};
const outcome={eventId:'e',session:event.session,family:event.family,direction:event.direction,entryTier:q.tier,instrumentKey:q.instrumentKey,timestamp:iso(start+31*MIN),outcome:{exitIq:run(rise)}};
const report=buildExitIqReport([event],[outcome],start+32*MIN);
assert.equal(report.matchedRows,1);assert.equal(report.policies[0].scenarios.BASE_1PT.pairedMeanDifferenceRupees,0);
assert.equal(report.promotionEligible,false);assert.equal(report.executionAllowed,false);
assert.equal(buildExitIqReport([event],[],start+32*MIN).missing.NOT_RECORDED_OR_PENDING,1);
assert.equal(buildExitIqReport([event],[outcome],start+30*MIN).matchedRows,0);
assert.equal(buildExitIqReport([event],[{...outcome,outcome:{exitIq:{...run(rise),entry:{...run(rise).entry,ask:99}}}}],start+32*MIN).matchedRows,0);
console.log('EXIT IQ PASS: identical paths, incumbent parity, stop-first gaps, causal ratchets, costs, bounded afterlife, missing coverage and matched results; research only');
