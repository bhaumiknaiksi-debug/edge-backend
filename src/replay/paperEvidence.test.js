'use strict';
const assert=require('node:assert/strict');
const {replayEvidence,plannerHash}=require('./paperEvidence');
const {createShadowTiming,buildTimingSource}=require('../engine/shadowTiming');
const {buildTradePlans}=require('../trading/readOnlyTradePlanner');
const {main}=require('../../scripts/replay-paper-evidence');
const time=x=>'2026-10-27T'+x+'+05:30';
const candidate={available:true,strategy:'LONG_CALL',legs:{buyLeg:{contractId:'NIFTY 27 OCT 23000 CE',instrumentKey:'NSE_FO|test',strike:23000,type:'CE',bid:99.8,ask:100,premium:100,delta:0.2}}};
const candidates={plans:{C:candidate}};
const candle=(t,close,high=110)=>[time(t),100,high,90,close];
const opening=[candle('09:15:00',100),candle('09:20:00',100),candle('09:25:00',100)];
const input={spot:115,support:50,resistance:150,marketPhase:'OPEN',dte:0,features:{trend30mPct:1,sessionChangePct:1},regime:{direction:'BULLISH'}};
const evaluate=createShadowTiming();
const snapshot=(t,raw)=>{
  const now=Date.parse(time(t));
  const s={recordType:'POLL_SNAPSHOT',id:t,timestamp:time(t),expiry:'2026-10-27',spot:115,support:{strike:100},resistance:{strike:140},
    researchCandidatePlans:structuredClone(candidates),signalTier:{gates:{market:true}},
    ruleSpec:{components:{exitHypotheses:{files:{'trading/readOnlyTradePlanner.js':plannerHash}}}},
    shadowTiming:evaluate({enabled:true,now,source:buildTimingSource(raw,now),candidates,input})};
  return s;
};
const first=snapshot('09:34:30',opening);
const crossed=[...opening,candle('09:30:00',115,120)];
const second=snapshot('09:35:00',crossed);
const third=snapshot('09:35:30',crossed);
assert.equal(second.shadowTiming.plans.C.shadowEntryReady,true,'actual shadow module supplies a crossing');
const records=[first,second,third,{recordType:'RESEARCH_CANDIDATE_OUTCOME',timestamp:time('10:00:00'),outcome:{mfePct:200}}];
const quotes=[first,second,third].map((s,i)=>({instrumentKey:'NSE_FO|test',expiry:'2026-10-27',receivedAt:s.timestamp,bid:i===2?106:99.8,ask:i===2?107:100,source:'TEST_ONLY'}));
const instruments=[{instrumentKey:'NSE_FO|test',expiry:'2026-10-27',lotSize:25,validFrom:time('09:15:00'),validThrough:time('15:30:00'),source:'TEST_ONLY_NOT_CURRENT_LOT_SIZE'}];
const options={reconstructPlans:true,quotes,instruments};
let report=replayEvidence({entries:records},options);
assert.equal(report.sessions[0].opens,1);assert.equal(report.sessions[0].closes,1);
assert.equal(report.excludedOutcomeRecords,1);assert.equal(report.readyRows,1);
assert.equal(report.executionAllowed,false);assert.equal(report.sessions[0].events.find(e=>e.type==='OPEN').entry,100);
assert.equal(report.sessions[0].events.find(e=>e.type==='OPEN').contract,JSON.stringify(['NSE_FO|test','2026-10-27']));
const laterQuote={...quotes[0],receivedAt:time('09:36:00'),bid:900,ask:901};
assert.deepEqual(replayEvidence(records,{...options,quotes:[...quotes,laterQuote]}).sessions,report.sessions,
  'appending future prices cannot change historical simulated decisions');
const before=JSON.stringify(records);replayEvidence(records,options);assert.equal(JSON.stringify(records),before);
assert.equal(replayEvidence(records,{...options,reconstructPlans:false}).sessions[0].opens,0);
assert.equal(replayEvidence(records,{...options,quotes:[]}).blockerCounts.MISSING_TIMESTAMPED_QUOTES,3);
assert.equal(replayEvidence(records,{...options,instruments:[]}).blockerCounts.MISSING_LOT_METADATA,3);
const unrecognized=structuredClone(records);unrecognized[1].shadowTiming.version='UNRECOGNIZED';
assert.equal(replayEvidence(unrecognized,options).sessions[0].opens,0);
const futureCandle=structuredClone(records);futureCandle[1].shadowTiming.plans.C.candleClosedAt=time('09:40:00');
assert.equal(replayEvidence(futureCandle,options).sessions[0].opens,0);
const wrongIdentity=structuredClone(records);wrongIdentity[1].shadowTiming.plans.C.contracts=['OTHER'];
assert.equal(replayEvidence(wrongIdentity,options).sessions[0].opens,0);
assert.equal(replayEvidence([second,third],options).sessions[0].opens,0,'already-confirmed baseline must not backfill entry');
const changed=structuredClone(records);changed[1].ruleSpec.components.exitHypotheses.files['trading/readOnlyTradePlanner.js']='old';
assert.equal(replayEvidence(changed,options).blockerCounts.PLANNER_VERSION_NOT_MATCHED,1);
const partial=structuredClone(records);delete partial[1].support;
assert.equal(replayEvidence(partial,options).sessions[0].opens,0,'missing original structure is not invented');
const futureQuotes=quotes.map(q=>({...q,receivedAt:time('09:36:00')}));
assert.throws(()=>replayEvidence(records,{...options,quotes:futureQuotes}),/DUPLICATE_QUOTE_TIMESTAMP/);
assert.equal(replayEvidence(records,{...options,quotes:futureQuotes.slice(0,1)}).sessions[0].opens,0);
const wrongExpiry=quotes.map(q=>({...q,expiry:'2026-11-03'}));
assert.equal(replayEvidence(records,{...options,quotes:wrongExpiry}).sessions[0].opens,0);
const frozen=structuredClone(records);
for(const s of frozen.filter(s=>s.recordType==='POLL_SNAPSHOT'))s.tradePlans=buildTradePlans({timestamp:s.timestamp,spot:s.spot,support:s.support,resistance:s.resistance,decision:{researchCandidatePlans:s.researchCandidatePlans}});
assert.equal(replayEvidence(frozen,{...options,reconstructPlans:false}).sessions[0].opens,1);
frozen[1].tradePlans.tiers.C.analysisAt=time('09:36:00');
assert.equal(replayEvidence(frozen,{...options,reconstructPlans:false}).sessions[0].opens,0,'future frozen plans cannot authorize historical entry');
assert.throws(()=>replayEvidence([second,second],options),/DUPLICATE_POLL_TIMESTAMP/);
assert.equal(replayEvidence(records,{...options,instruments:[...instruments,{...instruments[0],lotSize:65}]}).blockerCounts.AMBIGUOUS_LOT_METADATA,3);
assert.throws(()=>main([]),/INPUT_REQUIRED/);
assert.throws(()=>main(['--token','secret']),/INVALID_ARGUMENTS/);
console.log('Paper evidence PASS: real shadow crossing integration, unchanged contracts, source hashes, as-of quote joins, expiry/lot provenance, no baselines or outcomes as fills');
const captured=require('../../fixtures/paper-evidence-captured-20261028.json');
const actual=replayEvidence(captured,{reconstructPlans:true});
assert.equal(actual.pollSnapshots,1);
assert.equal(actual.sessions[0].opens,0);
assert.equal(actual.sessions[0].netPnl,null);
assert.equal(actual.blockerCounts.RECORDED_MARKET_NOT_OPEN,1);
assert.equal(actual.blockerCounts.MISSING_TIMESTAMPED_QUOTES,1);
assert.equal(actual.blockerCounts.MISSING_RECONSTRUCTION_INPUTS,1);
const cliReport=main(['--input',require.resolve('../../fixtures/paper-evidence-captured-20261028.json'),'--reconstruct-plans']);
assert.match(cliReport.inputSha256,/^[a-f0-9]{64}$/);
assert.equal(cliReport.sessions[0].opens,0);
console.log('Captured production schema PASS: after-hours legacy data remains non-tradable with no invented P&L');
