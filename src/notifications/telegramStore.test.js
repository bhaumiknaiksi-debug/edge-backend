'use strict';

const assert=require('node:assert/strict');
const {createTelegramStore,readSchema}=require('./telegramStore');
const SCHEMA=readSchema();
const {observationOf}=require('./telegramEvents');
const {fakeTelegramPool,decision}=require('./telegramTestHelpers');
(async()=>{
  const {fake,pool}=fakeTelegramPool();
  const store=createTelegramStore({pool,recipientKey:'owner'});
  const base=Date.parse('2026-10-26T05:00:00Z');
  const ctx=(time,ready)=>({now:time,observation:observationOf(decision(time,ready),time),phase:'OPEN',bootId:'boot',startedAt:base,dailySummary:true});
  await store.initialize();
  await store.checkpoint(ctx(base,false));
  const baseline=await store.loadState();
  fake.failMatch='INSERT INTO edge_telegram_outbox_v1';
  await assert.rejects(()=>store.checkpoint(ctx(base+10000,true)));
  assert.equal(fake.events.size,0,'event creation must roll back with its outbox');
  assert.equal(fake.outbox.size,0);
  assert.deepEqual(await store.loadState(),baseline,'cursor must roll back with a failed outbox insert');
  assert.equal(fake.releases,2,'connections released on success and rollback');
  fake.failMatch=null;
  await store.checkpoint(ctx(base+10000,true));
  assert.equal(fake.events.size,1);
  assert.equal(fake.outbox.size,1);
  await store.checkpoint(ctx(base+10000,true));
  assert.equal(fake.events.size,1,'duplicate source observations cannot duplicate evidence');
  const claimed=await store.claim(base+10000);
  assert.equal(claimed.attempts,1);
  assert.equal(fake.outbox.get(claimed.event.id).status,'SENDING');
  assert.equal(await store.claim(base+11000),null,'per-recipient pacing is persisted');
  const other=createTelegramStore({pool,recipientKey:'other-owner'});
  assert.equal(await other.claim(base+12000),null,'different recipient cannot claim an existing queue');
  await other.finish(claimed.event.id,'SENT',{messageId:123});
  assert.equal(fake.outbox.get(claimed.event.id).status,'SENDING');
  await store.finish(claimed.event.id,'PENDING',{error:'TELEGRAM_RATE_LIMIT',nextAttemptAt:new Date(base+30000).toISOString()});
  assert.equal(await store.claim(base+20000),null);
  const retried=await store.claim(base+30000);
  assert.equal(retried.attempts,2);
  // Restart after an unacknowledged claim must not repeat a possibly accepted send.
  const restarted=createTelegramStore({pool,recipientKey:'owner'});
  assert.equal(await restarted.claim(base+46000),null);
  assert.equal(fake.outbox.get(claimed.event.id).status,'UNCERTAIN');
  assert.equal(fake.outbox.get(claimed.event.id).error,'WORKER_INTERRUPTED');
  assert(fake.queries.some(sql=>sql.includes('FOR UPDATE OF q SKIP LOCKED')));
  assert(fake.queries.some(sql=>sql.includes('edge_telegram_state_v1 WHERE recipient_key=$1 FOR UPDATE')));
  assert(!fake.queries.some(sql=>/edge_evidence|edge_trade_ledger|edge_push/.test(sql)),'transport must not alter existing storage');
  assert(SCHEMA.includes('ON DELETE RESTRICT'));
  assert(!/DROP TABLE|TRUNCATE|DELETE FROM/i.test(SCHEMA));
  const concurrent=fakeTelegramPool();
  const serial=createTelegramStore({pool:concurrent.pool,recipientKey:'serial-owner'});
  await Promise.all([serial.checkpoint(ctx(base,false)),serial.checkpoint(ctx(base+10000,true))]);
  assert.equal(concurrent.fake.events.size,1,'per-producer transactions serialize concurrent checkpoint requests');
  const cooling=fakeTelegramPool();
  const recipient=createTelegramStore({pool:cooling.pool,recipientKey:'cooling-owner'});
  await recipient.checkpoint(ctx(base,false));
  await recipient.checkpoint(ctx(base+10000,true));
  const limited=await recipient.claim(base+10000);
  await recipient.checkpoint(ctx(base+20000,false));
  const cooldownUntil=base+70000;
  await recipient.finish(limited.event.id,'PENDING',{error:'TELEGRAM_RATE_LIMIT',
    nextAttemptAt:new Date(cooldownUntil).toISOString(),cooldownUntil});
  assert.equal(await recipient.claim(base+20000),null,'429 blocks other pending events for the entire recipient');
  const recovered=createTelegramStore({pool:cooling.pool,recipientKey:'cooling-owner'});
  await recovered.checkpoint(ctx(base+30000,false));
  assert.equal((await recovered.loadState()).cooldownUntil,cooldownUntil,'checkpoint and restart preserve cooldown');
  assert.equal(await recovered.claim(cooldownUntil-1),null,'cooldown applies through the last millisecond');
  const independent=createTelegramStore({pool:cooling.pool,recipientKey:'independent-owner'});
  await independent.checkpoint(ctx(base,false));await independent.checkpoint(ctx(base+10000,true));
  assert(await independent.claim(base+30000),'another recipient is not blocked');
  const exhausted=await recovered.claim(cooldownUntil);
  assert(exhausted,'claim resumes at the cooldown deadline');
  await recovered.finish(exhausted.event.id,'FAILED',{error:'TELEGRAM_RATE_LIMIT',cooldownUntil:base+130000});
  assert.equal(await recovered.claim(base+80000),null,'exhausting retries still cools down all queued events');
  await recovered.finish(exhausted.event.id,'FAILED',{cooldownUntil:base+90000});
  assert.equal((await recovered.loadState()).cooldownUntil,base+130000,'a shorter cooldown cannot weaken an existing one');
  const next=await recovered.claim(base+130000);
  const beforeFailure=await recovered.loadState();
  cooling.fake.failMatch='UPDATE edge_telegram_state_v1';
  await assert.rejects(()=>recovered.finish(next.event.id,'PENDING',{
    nextAttemptAt:new Date(base+200000).toISOString(),cooldownUntil:base+200000}));
  assert.equal(cooling.fake.outbox.get(next.event.id).status,'SENDING','cooldown and outbox transition roll back atomically');
  assert.deepEqual(await recovered.loadState(),beforeFailure);
  console.log('Telegram store PASS: atomic event/outbox/cursor, rollback, idempotency, recipient isolation, pacing, retries and ambiguous-lease recovery');
})().catch(error=>{console.error(error);process.exitCode=1;});
