'use strict';
const assert=require('node:assert/strict');
const {reconstruct,observeOpenMark,summary,assessFlatEntry,monthOf}=require('./monthlyRiskCore');
const date=s=>Date.parse(s+'+05:30'), now=date('2026-11-16T12:00:00');
const trades=(id,day,pnl,buys=65)=>({id,closedAt:date(day+'T12:00:00'),netPnl:pnl,buys});
const wrap=t=>({trade:t});
const a=trades('a','2026-11-09',-724), b=trades('b','2026-11-09',36.5);
const prior=trades('prior','2026-10-30',0,0);
const input={now,archived:[wrap(prior),wrap(a),wrap(b)],hot:[],archivedTrades:3,archivedPnl:-687.5,readLimit:100};
const restore=(extra={})=>reconstruct({...input,...extra});
const initial=restore();
assert.deepEqual(summary(initial),{month:'2026-11',locked:false,lockedAt:null,lockBasis:null,realizedPaise:-68750,remainingPaise:631250,capitalPaise:931250});
const loss=trades('loss','2026-11-15',-6312.5);
const atLimit=restore({hot:[loss]});
assert.equal(summary(atLimit).remainingPaise,0);
assert.equal(atLimit.locked,true);
assert.equal(atLimit.lockBasis,'REALIZED');
assert.equal(assessFlatEntry(atLimit,{now,flat:true,plannedLoss:100,entryOutlay:200}),'MONTHLY_LOSS_LOCK');
const gain=trades('gain','2026-11-16',1000);
assert.equal(restore({hot:[loss,gain]}).locked,true,'later profit cannot undo a previous realized threshold');
assert.equal(restore({hot:[gain]}).locked,false);
const marked=observeOpenMark(initial,{now:now+1000,markAt:now+1000,netOpenPnl:-6312.5});
assert.equal(marked.locked,true);assert.equal(marked.lockBasis,'MARKED');
assert.equal(observeOpenMark(marked,{now:now+2000,markAt:now+2000,netOpenPnl:100}).locked,true);
const recovered=restore({now:now+3000,previous:JSON.parse(JSON.stringify(marked))});
assert.equal(recovered.locked,true,'JSON persistence and reconstruction preserve the marked lock');
const archivedLoss=restore({archived:[...input.archived,wrap(loss)],archivedTrades:4,archivedPnl:-7000});
assert.deepEqual(summary(archivedLoss),summary(atLimit),'moving a trade from hot to archive does not change the lock or budget');
const december=date('2026-12-01T00:00:00');
assert.equal(monthOf(december-1),'2026-11');assert.equal(monthOf(december),'2026-12');
const nextMonth=restore({now:december,previous:recovered});
assert.equal(nextMonth.locked,false);assert.equal(summary(nextMonth).realizedPaise,0);
assert.equal(assessFlatEntry(initial,{now,flat:true,plannedLoss:8000,entryOutlay:9000}),'MONTHLY_RISK_BUDGET');
assert.equal(assessFlatEntry(initial,{now,flat:true,plannedLoss:500,entryOutlay:9500}),'CAPITAL_LIMIT');
assert.equal(assessFlatEntry(initial,{now,flat:false,plannedLoss:500,entryOutlay:6000}),'EXPOSURE_ALREADY_EXISTS');
assert.equal(assessFlatEntry(initial,{now,flat:true,plannedLoss:500,entryOutlay:6000}),'MONTHLY_BUDGET_ELIGIBLE');
assert.equal(assessFlatEntry(initial,{now:now+10001,flat:true,plannedLoss:500,entryOutlay:6000}),'MONTHLY_STATE_STALE');
for(const extra of [{archivedTrades:2},{archivedPnl:-600},{hot:[a]},{readLimit:3},{hot:[{...loss,netPnl:NaN}]},{hot:[{...loss,closedAt:now+1}]},{hot:[{...loss,buys:0}]}]){
  assert.throws(()=>restore(extra),/MONTHLY_RISK_EVIDENCE_INVALID/);
}
assert.throws(()=>observeOpenMark(initial,{now:now+20000,markAt:now,netOpenPnl:-7000}),/MONTHLY_RISK_EVIDENCE_INVALID/);
assert.throws(()=>observeOpenMark(initial,{now,markAt:now+1,netOpenPnl:-7000}),/MONTHLY_RISK_EVIDENCE_INVALID/);
assert.throws(()=>observeOpenMark(initial,{now,markAt:now,netOpenPnl:null}),/MONTHLY_RISK_EVIDENCE_INVALID/);
console.log('monthlyRiskCore PASS: net costs, archive validation, exact threshold, durable sticky lock, quote freshness, IST month boundary, affordability');
